const { chromium, webkit, devices } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = 'https://maison-miroir.fr';
const browserName = process.argv[2] || 'chrome';
(async () => {
  fs.mkdirSync('.qa', { recursive: true });
  const engine = browserName === 'webkit' ? webkit : chromium;
  const browser = await engine.launch({ headless: true, ...(browserName === 'chrome' ? { channel: 'chrome' } : {}) });
  const context = await browser.newContext(browserName === 'webkit' ? devices['iPhone 13'] : { viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const result = { browser: browserName };
  try {
    await page.goto(base + '/product/modest-era', { waitUntil: 'networkidle' });
    const reject = page.getByRole('button', { name: 'Tout refuser', exact: true });
    if (await reject.count()) await reject.click();
    await page.locator('input[type="number"]').first().fill('1');
    await page.getByRole('button', { name: 'Ajouter au panier', exact: true }).click();
    await page.locator('.mm-cart-modal[open]').waitFor();
    await page.getByRole('link', { name: 'VOIR LE PANIER', exact: true }).click();
    await page.waitForURL(base + '/panier', { timeout: 12000 });
    result.drawerNavigation = true;
    await page.getByRole('heading', { name: 'Votre panier (1)', exact: true }).waitFor();
    await page.reload({ waitUntil: 'networkidle' });
    await page.getByRole('heading', { name: 'Votre panier (1)', exact: true }).waitFor();
    result.reloadPersistence = true;
    assert.equal(await page.getByText(/Domicile/).count(), 0);
    result.homeHidden = true;
    assert.ok(/34[.,]00/.test((await page.locator('body').innerText()).replace(/[\s\u00a0\u202f]/g, '')));
    result.totalWithoutPromotion = '34.00';
    await page.getByRole('button', { name: 'Augmenter la quantité', exact: true }).click();
    await page.getByRole('heading', { name: 'Votre panier (2)', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Diminuer la quantité', exact: true }).click();
    await page.getByRole('heading', { name: 'Votre panier (1)', exact: true }).waitFor();
    result.quantityChanges = true;
    await page.getByLabel('Code promotionnel', { exact: true }).fill('FIRSTPRINCESS1');
    const promotion = page.waitForResponse(r => r.url().includes('/api/promotions/validate'));
    await page.getByRole('button', { name: 'Appliquer', exact: true }).click();
    const promo = await promotion;
    assert.equal(promo.status(), 200);
    assert.equal((await promo.json()).discountCents, 299);
    await page.getByText('Réduction FIRSTPRINCESS1', { exact: true }).waitFor();
    result.promotionInCart = true;
    await page.getByRole('link', { name: 'Passer au paiement', exact: true }).click();
    await page.waitForURL(base + '/checkout');
    await page.getByText('Réduction FIRSTPRINCESS1', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Code promotionnel', { exact: true }).inputValue(), 'FIRSTPRINCESS1');
    result.promotionPassedToCheckout = true;
    await page.getByLabel('Code postal *', { exact: true }).fill('78300');
    const search = page.waitForResponse(r => r.url().includes('/api/shipping/mondial-relay/points'));
    await page.getByRole('button', { name: 'Rechercher un Point Relais', exact: true }).click();
    const response = await search;
    assert.equal(response.status(), 200);
    const payload = await response.json();
    assert.ok(payload.points.length && payload.points.every(p => p.source === 'production' && p.proof));
    await page.locator('input[name="mondial-relay-point"]').first().check();
    const relay = await page.evaluate(() => JSON.parse(localStorage.getItem('mm:cart:v1')).relayPoint.id);
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('mm:cart:v1')).relayPoint.id), relay);
    result.realRelayPersisted = true;
    await page.getByText('Réduction FIRSTPRINCESS1', { exact: true }).waitFor();
    assert.ok(/31[.,]01/.test((await page.locator('body').innerText()).replace(/[\s\u00a0\u202f]/g, '')));
    result.promotionProductsOnly = true;
    const config = await (await page.request.get(base + '/api/shipping/config')).json();
    result.paymentConditions = Object.fromEntries(['shopOpen', 'paymentsEnabled', 'realShippingEnabled', 'manualShippingReady', 'fulfillmentReady'].map(k => [k, config[k]]));
    await page.goto(base + '/panier', { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: 'Supprimer', exact: true }).click();
    await page.getByText('Votre panier est vide.', { exact: true }).waitFor();
    result.removal = true;
    assert.deepEqual(errors, []);
    result.pageErrors = errors;
    result.success = true;
  } catch (error) {
    result.success = false;
    result.error = error.message;
    result.pathname = new URL(page.url()).pathname;
    await page.screenshot({ path: `.qa/purchase-${browserName}-failure.png`, fullPage: true });
    fs.writeFileSync(`.qa/purchase-${browserName}-failure.txt`, await page.locator('body').innerText());
    process.exitCode = 1;
  } finally {
    fs.writeFileSync(`.qa/purchase-${browserName}-result.json`, JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
    await browser.close();
  }
})();
